create table if not exists public.intercession_prayer_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  theme_id text not null,
  started_at timestamptz not null,
  finished_at timestamptz not null,
  duration_seconds integer not null check (duration_seconds between 0 and 600),
  created_at timestamptz not null default now(),
  constraint intercession_prayer_sessions_finish_after_start check (finished_at >= started_at)
);

create index if not exists intercession_prayer_sessions_user_created_idx
  on public.intercession_prayer_sessions (user_id, created_at desc);

alter table public.intercession_prayer_sessions enable row level security;
revoke all on table public.intercession_prayer_sessions from anon;
revoke all on table public.intercession_prayer_sessions from authenticated;
grant select, insert on table public.intercession_prayer_sessions to authenticated;
grant all on table public.intercession_prayer_sessions to service_role;

drop policy if exists "Users can view their own intercession sessions" on public.intercession_prayer_sessions;
create policy "Users can view their own intercession sessions"
  on public.intercession_prayer_sessions for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can record their own intercession sessions" on public.intercession_prayer_sessions;
create policy "Users can record their own intercession sessions"
  on public.intercession_prayer_sessions for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create table if not exists public.intercession_prayer_reminders (
  user_id uuid primary key references auth.users (id) on delete cascade,
  timezone text not null default 'UTC',
  schedule jsonb not null default '{}'::jsonb check (jsonb_typeof(schedule) = 'object'),
  updated_at timestamptz not null default now()
);

alter table public.intercession_prayer_reminders enable row level security;
revoke all on table public.intercession_prayer_reminders from anon;
revoke all on table public.intercession_prayer_reminders from authenticated;
grant select, insert, update on table public.intercession_prayer_reminders to authenticated;
grant all on table public.intercession_prayer_reminders to service_role;

drop policy if exists "Users can view their own intercession reminders" on public.intercession_prayer_reminders;
create policy "Users can view their own intercession reminders"
  on public.intercession_prayer_reminders for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own intercession reminders" on public.intercession_prayer_reminders;
create policy "Users can create their own intercession reminders"
  on public.intercession_prayer_reminders for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own intercession reminders" on public.intercession_prayer_reminders;
create policy "Users can update their own intercession reminders"
  on public.intercession_prayer_reminders for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
