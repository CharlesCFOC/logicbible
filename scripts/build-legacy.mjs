import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const files = JSON.parse(readFileSync(join(root, 'scripts/legacy-manifest.json'), 'utf8'));
const source = files.map(file => `\n/* Source: ${file} */\n${readFileSync(join(root, file), 'utf8')}\n;`).join('\n');
mkdirSync(join(root, 'assets'), { recursive: true });
writeFileSync(join(root, 'assets/legacy.js'), `/* Generated by build:legacy. Edit the source files in scripts/legacy-manifest.json. */\n${source}\n`);
console.log(`Built the legacy browser bundle from ${files.length} source files.`);
